function adj(codigo, nombre, mime, kb, fecha) {
  const y = codigo.slice(4, 8);
  const m = codigo.slice(8, 10);
  const d = codigo.slice(10, 12);
  return {
    nombre_archivo: nombre,
    tipo_mime: mime,
    peso_kb: kb,
    url_storage: `evidencias/${y}/${m}/${d}/${codigo}/${nombre}`,
    fecha_carga: new Date(fecha),
  };
}

